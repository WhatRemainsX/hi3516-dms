/*
 * 【说明】rtp_h264：把"一个 NAL 单元"封装成一个或多个 RTP 包（RFC 6184 规定的 H.264 RTP 打包方式）。
 *   RTP（Real-time Transport Protocol）= 实时传输协议，专门用来在网络上传音视频，
 *   通常放在 UDP 上发送。每个 RTP 包 = 12 字节 RTP 头 + 载荷。
 *   本模块只负责"组装包"，不管怎么发送：组装好后调用一个回调函数（rtp_send_cb），由使用者决定
 *   是用 UDP 发出去还是别的方式。这样以后换成 TCP interleaved 方式时，本模块一行都不用改。
 *
 *   【为什么要分片】以太网一个包最多约 1500 字节（MTU）。一个 I 帧可能几十 KB，一个包装不下，
 *   所以大于 1400 字节的 NAL 要切成多片，用 FU-A 格式发送；接收端再把它们拼回来。
 *   小于等于 1400 字节的直接放进一个包（Single NAL Unit 模式）。
 */

#ifndef RTP_H264_H
#define RTP_H264_H

#include <stdint.h>
#include <stddef.h>
/*
RTP 固定头（12 字节）
 字节:    0               1               2               3
 位:      0 1 2 3 4 5 6 7 0 1 2 3 4 5 6 7 0 1 2 3 4 5 6 7 0 1 2 3 4 5 6 7
         +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
 0~3     |V=2|P|X|  CC   |M|     PT      |       序号 seq（16位）         |
         +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
 4~7     |                    时间戳 timestamp（32位）                    |
         +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
 8~11    |                    同步源 SSRC（32位）                         |
         +-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+-+
字段 位数 取值 作用
V	2	2	RTP 版本
P	1	0	末尾有无填充
X	1	0	有无扩展头
CC	4	0	附加的 CSRC 个数
M	1	帧末包为 1	标记"这一帧结束了"
PT	7	96	载荷类型，对应 SDP 里的 rtpmap:96
seq	16	逐包 +1	接收端据此发现丢包、重新排序
timestamp	32	90 kHz	同一帧所有包相同
SSRC	32	固定值	区分不同的流
*/

/* NAL 头（1 字节）
位:   7   6 5   4 3 2 1 0
      +---+-----+---------+
      | F | NRI |  Type   |
      +---+-----+---------+

 例: 0x65 = 0 | 11 | 00101   → F=0, NRI=3(重要), Type=5 (IDR)
     0x67 = 0 | 11 | 00111   → Type=7 (SPS)
     0x68 = 0 | 11 | 01000   → Type=8 (PPS)
     0x41 = 0 | 10 | 00001   → Type=1 (普通P帧)
单 NAL 包为：
编码器输出:  00 00 00 01 | 67 42 00 1F AA
             └─ 起始码 ─┘  └──── NAL ────┘
                  丢掉            ↓ 原样拷贝
            ┌──────────────┬─────────────────┐
RTP 包:     │ RTP 头 12字节 │ 67 42 00 1F AA  │
            └──────────────┴─────────────────┘
*/

/*
FU-A 包的结构
┌──────────────┬──────────────┬────────────┬────────────────────┐
│  RTP 头 12B   │ FU indicator │ FU header  │ 这一片的 NAL 数据   │
└──────────────┴──────────────┴────────────┴────────────────────┘

FU indicator（第 1 个字节）
   7   6 5   4 3 2 1 0
 +---+-----+---------+
 | F | NRI | Type=28 |
 +---+-----+---------+
F（禁止位）：正常为 0。如果中间设备发现数据有错，会把它置 1
NRI（重要程度）：2 位，0–3，数值越大越重要。
Type = 28：告诉接收端"这是 FU-A"。

FU header（第 2 个字节）
   7   6   5   4 3 2 1 0
 +---+---+---+---------+
 | S | E | R |  Type   |
 +---+---+---+---------+

S（Start）：这是该 NAL 的第一片时为 1。
E（End）：这是该 NAL 的最后一片时为 1。
R（保留）：必须为 0。
Type：原 NAL 的真实类型，例如 IDR 是 5，P 帧是 1。

*/

/*
 * 【说明】下面三个常量：
 *    RTP_HEADER_SIZE     ：RTP 固定头 12 字节
 *    RPT_MAX_PAYLOAD     ：单包载荷最多 1400 字节（名字里的 RPT 是 RTP 的笔误，但所有文件统一用它，没有影响）。
 *                          留余量是因为：1500(MTU) - 20(IP头) - 8(UDP头) - 12(RTP头) = 1460，
 *                          再留一点给隧道/VPN 等额外开销，1400 比较保险
 *    RTP_PAYLOAD_TYPE96  ：载荷类型号 96。0~95 大多被固定的老编码占用，96~127 是"动态"类型，
 *                          由 SDP 里的 a=rtpmap:96 H264/90000 声明"96 代表 H.264"，
 *                          所以这里的 96 必须与 SDP 里的 96 一致。
 */
#define RTP_HEADER_SIZE 12 /* RTP 固定头长度 */
#define RPT_MAX_PAYLOAD 1400 /* 单包载荷上限，给以太网 MTU 留余量 */
#define RTP_PAYLOAD_TYPE96 96 /* RTP 负载类型，动态分配，H.264 常用 96 */

/* 打包好一个完整 RTP 包后调用它；返回 0 成功 */
/*
 * 【说明】函数指针类型：发送回调。参数是(整个 RTP 包的首地址, 长度, 使用者私有指针)，返回 0 表示成功。
 *   rtp_sender.c 里的 rtp_udp_send 就是一个符合这个形状的函数。
 */
typedef int (*rtp_send_cb)(const uint8_t *pkt, size_t len, void *arg);

/*
 * 【说明】每个 RTSP 客户端各有一份独立的 rtp_h264_ctx，所以每个客户端的序列号(seq)都是独立递增的。
 *    seq  ：序列号。每发一个包 +1。接收端靠它发现丢包、纠正乱序。16 位，到 65535 后自动回绕到 0。
 *    ssrc ：同步源标识。随机/固定值，用来区分"这是哪一路流"。
 *    send / arg：发包回调及其私有参数。
 */
/* H.264 RTP 打包上下文，保存发送序号、同步源和发包回调。 */
typedef struct {
    uint16_t seq; /* RTP 序列号 */
    rtp_send_cb send; /* 发送回调函数 */
    uint32_t ssrc;/* RTP 同步源标识符 */
    void    *arg; /* 发送回调函数参数 */
} rtp_h264_ctx;

/// 初始化 RTP H264 上下文
void rtp_h264_init(rtp_h264_ctx *ctx, uint32_t ssrc, rtp_send_cb send, void *arg);

/// 发送一个 H264 NAL 单元
/*
 * 【说明】参数：
 *    nal     ：指向 NAL 本体（不含 00 00 00 01 起始码，第一个字节就是 NAL 头）
 *    len     ：NAL 长度
 *    ts      ：RTP 时间戳（90 kHz 时钟），同一帧的所有包必须相同
 *    marker  ：RTP 头里的 M 位。只有"一帧的最后一个包"才为 1，告诉接收端"这一帧结束了，可以解码显示了"
 */
int rtp_h264_send_nal(rtp_h264_ctx *ctx, const uint8_t *nal, size_t len, uint32_t ts,int marker);

#endif
